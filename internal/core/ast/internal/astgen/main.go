// Command astgen reads grammar/heron.ungram and writes the kind enum for
// internal/core/syntax and the typed views for internal/core/ast.
//
//	go run ./internal/core/ast/internal/astgen -grammar grammar/heron.ungram \
//	    -syntax internal/core/syntax/kinds_gen.go -ast internal/core/ast/nodes_gen.go
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
	"unicode"
)

type elem struct {
	label string
	kind  string
	card  byte // 0, '?' or '*'
}

type rule struct {
	name  string
	alts  []string // for sums
	elems []elem   // for nodes
}

type grammar struct {
	tokens []string
	rules  []*rule
	byName map[string]*rule
	isTok  map[string]bool
}

func parse(path string) (*grammar, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	g := &grammar{byName: map[string]*rule{}, isTok: map[string]bool{}}
	// Join continuation lines (starting with whitespace) onto their rule.
	var logical []string
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line := sc.Text()
		if i := strings.Index(line, "//"); i >= 0 {
			line = line[:i]
		}
		if strings.TrimSpace(line) == "" {
			continue
		}
		if line[0] == ' ' || line[0] == '\t' {
			if len(logical) == 0 {
				return nil, fmt.Errorf("continuation without a rule: %q", line)
			}
			logical[len(logical)-1] += " " + strings.TrimSpace(line)
			continue
		}
		logical = append(logical, strings.TrimSpace(line))
	}
	for _, l := range logical {
		if strings.HasPrefix(l, "token ") {
			for _, t := range strings.Fields(l)[1:] {
				g.tokens = append(g.tokens, t)
				g.isTok[t] = true
			}
			continue
		}
		name, rhs, ok := strings.Cut(l, "=")
		if !ok {
			return nil, fmt.Errorf("not a rule: %q", l)
		}
		r := &rule{name: strings.TrimSpace(name)}
		if strings.Contains(rhs, "|") {
			for _, a := range strings.Split(rhs, "|") {
				r.alts = append(r.alts, strings.TrimSpace(a))
			}
		} else {
			for _, f := range strings.Fields(rhs) {
				e := elem{}
				if lab, k, ok := strings.Cut(f, ":"); ok {
					e.label, f = lab, k
				}
				if n := len(f); n > 0 && (f[n-1] == '?' || f[n-1] == '*') {
					e.card, f = f[n-1], f[:n-1]
				}
				e.kind = f
				r.elems = append(r.elems, e)
			}
		}
		if g.byName[r.name] != nil {
			return nil, fmt.Errorf("rule %s defined twice", r.name)
		}
		g.rules = append(g.rules, r)
		g.byName[r.name] = r
	}
	for _, r := range g.rules {
		for _, a := range r.alts {
			if g.byName[a] == nil {
				return nil, fmt.Errorf("%s: unknown alternative %s", r.name, a)
			}
		}
		for _, e := range r.elems {
			if g.byName[e.kind] == nil && !g.isTok[e.kind] {
				return nil, fmt.Errorf("%s: unknown element %s", r.name, e.kind)
			}
		}
	}
	return g, nil
}

func (g *grammar) nodes() []*rule {
	var out []*rule
	for _, r := range g.rules {
		if r.alts == nil {
			out = append(out, r)
		}
	}
	return out
}

func (g *grammar) sums() []*rule {
	var out []*rule
	for _, r := range g.rules {
		if r.alts != nil {
			out = append(out, r)
		}
	}
	return out
}

// leaves returns the node kinds a sum covers, transitively.
func (g *grammar) leaves(name string) []string {
	seen := map[string]bool{}
	var out []string
	var walk func(string)
	walk = func(n string) {
		r := g.byName[n]
		if r.alts == nil {
			if !seen[n] {
				seen[n] = true
				out = append(out, n)
			}
			return
		}
		for _, a := range r.alts {
			walk(a)
		}
	}
	walk(name)
	return out
}

// sumsOf returns the sums a node kind belongs to, directly or through others.
func (g *grammar) sumsOf(node string) []string {
	var out []string
	for _, s := range g.sums() {
		for _, l := range g.leaves(s.name) {
			if l == node {
				out = append(out, s.name)
				break
			}
		}
	}
	return out
}

func genSyntax(g *grammar) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by astgen from grammar/heron.ungram. DO NOT EDIT.\n\npackage syntax\n\n")
	b.WriteString("const (\n\tKindNone Kind = iota\n")
	for _, t := range g.tokens {
		fmt.Fprintf(&b, "\t%s\n", t)
	}
	b.WriteString("\tfirstNodeKind\n")
	for _, n := range g.nodes() {
		fmt.Fprintf(&b, "\t%s\n", n.name)
	}
	b.WriteString("\tkindCount\n)\n\n")
	b.WriteString("var kindNames = [...]string{\n\tKindNone: \"None\",\n")
	for _, t := range g.tokens {
		fmt.Fprintf(&b, "\t%s: %q,\n", t, t)
	}
	for _, n := range g.nodes() {
		fmt.Fprintf(&b, "\t%s: %q,\n", n.name, n.name)
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func plural(s string) string {
	switch {
	case strings.HasSuffix(s, "s"):
		return s + "es"
	case strings.HasSuffix(s, "y"):
		return s[:len(s)-1] + "ies"
	}
	return s + "s"
}

func export(s string) string {
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

func genAST(g *grammar) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by astgen from grammar/heron.ungram. DO NOT EDIT.\n\npackage ast\n\n")
	b.WriteString("import \"github.com/helightdev/specs-v0/internal/core/syntax\"\n\n")
	for _, s := range g.sums() {
		fmt.Fprintf(&b, "// %s is one of: %s.\n//\n//sumtype:decl\ntype %s interface {\n\tNode\n\tis%s()\n}\n\n",
			s.name, strings.Join(g.leaves(s.name), ", "), s.name, s.name)
		fmt.Fprintf(&b, "// Is%sKind reports whether nodes of kind k are %s.\nfunc Is%sKind(k syntax.Kind) bool {\n\tswitch k {\n\tcase ", s.name, s.name, s.name)
		var ks []string
		for _, l := range g.leaves(s.name) {
			ks = append(ks, "syntax."+l)
		}
		b.WriteString(strings.Join(ks, ", "))
		b.WriteString(":\n\t\treturn true\n\t}\n\treturn false\n}\n\n")
		fmt.Fprintf(&b, "// As%s returns the typed view of n as %s, or nil.\nfunc As%s(n *syntax.Node) %s {\n\tif n == nil {\n\t\treturn nil\n\t}\n\tswitch n.Kind {\n", s.name, s.name, s.name, s.name)
		for _, l := range g.leaves(s.name) {
			fmt.Fprintf(&b, "\tcase syntax.%s:\n\t\treturn %s{n}\n", l, l)
		}
		b.WriteString("\t}\n\treturn nil\n}\n\n")
	}
	for _, n := range g.nodes() {
		fmt.Fprintf(&b, "// %s is a typed view of a syntax.%s node.\ntype %s struct{ N *syntax.Node }\n\n", n.name, n.name, n.name)
		fmt.Fprintf(&b, "// Syntax returns the underlying node.\nfunc (n %s) Syntax() *syntax.Node { return n.N }\n\n", n.name)
		for _, s := range g.sumsOf(n.name) {
			fmt.Fprintf(&b, "func (%s) is%s() {}\n", n.name, s)
		}
		b.WriteString("\n")
		// Count occurrences of each kind to index labeled duplicates.
		occ := map[string]int{}
		used := map[string]bool{}
		for _, e := range n.elems {
			idx := occ[e.kind]
			occ[e.kind]++
			name := e.kind
			if e.label != "" {
				name = e.label
			}
			name = export(name)
			if e.card == '*' && e.label == "" {
				name = plural(name)
			}
			if used[name] {
				continue
			}
			used[name] = true
			switch {
			case g.isTok[e.kind] && e.card == '*':
				fmt.Fprintf(&b, "func (n %s) %s() []*syntax.Token { return tokens(n.N, syntax.%s) }\n", n.name, name, e.kind)
			case g.isTok[e.kind]:
				fmt.Fprintf(&b, "func (n %s) %s() *syntax.Token { return token(n.N, syntax.%s, %d) }\n", n.name, name, e.kind, idx)
			case g.byName[e.kind].alts != nil && e.card == '*':
				fmt.Fprintf(&b, "func (n %s) %s() []%s {\n\tvar out []%s\n\tfor _, c := range children(n.N, Is%sKind) {\n\t\tout = append(out, As%s(c))\n\t}\n\treturn out\n}\n", n.name, name, e.kind, e.kind, e.kind, e.kind)
			case g.byName[e.kind].alts != nil:
				fmt.Fprintf(&b, "func (n %s) %s() %s { return As%s(child(n.N, Is%sKind, %d)) }\n", n.name, name, e.kind, e.kind, e.kind, idx)
			case e.card == '*':
				fmt.Fprintf(&b, "func (n %s) %s() []%s {\n\tvar out []%s\n\tfor _, c := range children(n.N, kindIs(syntax.%s)) {\n\t\tout = append(out, %s{c})\n\t}\n\treturn out\n}\n", n.name, name, e.kind, e.kind, e.kind, e.kind)
			default:
				fmt.Fprintf(&b, "func (n %s) %s() %s { return %s{child(n.N, kindIs(syntax.%s), %d)} }\n", n.name, name, e.kind, e.kind, e.kind, idx)
			}
		}
		b.WriteString("\n")
	}
	// A generic Cast over every node kind.
	b.WriteString("// Cast returns the typed view of n, or nil for a nil node.\nfunc Cast(n *syntax.Node) Node {\n\tif n == nil {\n\t\treturn nil\n\t}\n\tswitch n.Kind {\n")
	var names []string
	for _, n := range g.nodes() {
		names = append(names, n.name)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&b, "\tcase syntax.%s:\n\t\treturn %s{n}\n", n, n)
	}
	b.WriteString("\t}\n\treturn nil\n}\n")
	return b.Bytes()
}

func write(path string, src []byte) {
	out, err := format.Source(src)
	if err != nil {
		fmt.Fprintf(os.Stderr, "%s: %v\n%s", path, err, src)
		os.Exit(1)
	}
	if err := os.WriteFile(path, out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func main() {
	gram := flag.String("grammar", "grammar/heron.ungram", "grammar description")
	syn := flag.String("syntax", "internal/core/syntax/kinds_gen.go", "kind enum output")
	ast := flag.String("ast", "internal/core/ast/nodes_gen.go", "typed views output")
	flag.Parse()
	g, err := parse(*gram)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	write(*syn, genSyntax(g))
	write(*ast, genAST(g))
}
