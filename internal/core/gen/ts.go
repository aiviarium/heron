// TS writes `.heron/types.ts`, the TS types of every type and enum the
// project and its packages declare.
func TS(in *Input) ([]registry.GeneratedFile, error) {
	g := &tsGen{c: in.Checker}
	trees := []*resolve.Tree{in.Tree}
	seen := map[*resolve.Package]bool{}
	var pkgs func(*resolve.Tree)
	pkgs = func(t *resolve.Tree) {
		for _, p := range t.Imports {
			if seen[p] || p.Tree == nil {
				continue
			}
			seen[p] = true
			if p.Tree.Entry == nil || !p.Tree.Entry.ID.IsStd() {
				trees = append(trees, p.Tree)
			}
			pkgs(p.Tree)
		}
	}
	pkgs(in.Tree)
	root := &tsNS{children: map[string]*tsNS{}}
	for _, t := range trees {
		t.Walk(func(n *resolve.Node) {
			if n.Shape == resolve.ShapeMounted || n.Decl.N == nil {
				return
			}
			switch {
			case g.c.IsEnum(n) && n.Name != "":
				root.at(nsPath(n)).decls = append(root.at(nsPath(n)).decls, g.enum(n))
			case g.c.IsType(n) && n.Name != "" && types.IsStd(g.c.KindOf(n), "types", "types.type"):
				root.at(nsPath(n)).decls = append(root.at(nsPath(n)).decls, g.record(n))
			case g.c.IsError(n) && n.Name != "" && (n.Parent == nil || g.c.KindOf(n.Parent) == nil):
				// An error of a data model, outside a kind's body, as a
				// record of its members that extends its parent's.
				root.at(nsPath(n)).decls = append(root.at(nsPath(n)).decls, g.record(n))
			}
		})
	}
	var b strings.Builder
	b.WriteString("// Code generated by `heron generate ts` from the Heron tree. DO NOT EDIT.\n")
	b.WriteString(tsPrelude)
	root.write(&b, "", true)

	return []registry.GeneratedFile{
		{Path: ".heron/types.ts", Content: []byte(b.String()), Ignored: true},
	}, nil
}

// tsPrelude declares the TS types the built-in Heron types map to that TS
// lacks, so types.ts imports nothing.
const tsPrelude = `/** A decimal fraction as its text, so amounts of money stay exact. */
export type Decimal = string;
/** A length of time, in whole milliseconds. */
export type Duration = number;
/** A reference to a node of the tree, by its path. */
export type Ref = string;
/** An mdast root, as a Prose value is written. */
export interface MdastRoot {
  type: "root";
  children: unknown[];
  [key: string]: unknown;
}

`

type tsGen struct {
	c *types.Checker
}

// tsNS is a namespace of types.ts.
type tsNS struct {
	children map[string]*tsNS
	decls    []string
}

func (ns *tsNS) at(segs []string) *tsNS {
	for _, s := range segs {
		c := ns.children[s]
		if c == nil {
			c = &tsNS{children: map[string]*tsNS{}}
			ns.children[s] = c
		}
		ns = c
	}
	return ns
}

func (ns *tsNS) write(b *strings.Builder, indent string, top bool) {
	for _, d := range ns.decls {
		for _, l := range strings.Split(strings.TrimRight(d, "\n"), "\n") {
			b.WriteString(indent + l + "\n")
		}
		b.WriteString("\n")
	}
	names := make([]string, 0, len(ns.children))
	for k := range ns.children {
		names = append(names, k)
	}
	sort.Strings(names)
	for _, k := range names {
		kw := "export namespace"
		if top {
			kw = "export declare namespace"
		}
		fmt.Fprintf(b, "%s%s %s {\n", indent, kw, k)
		ns.children[k].write(b, indent+"  ", false)
		fmt.Fprintf(b, "%s}\n\n", indent)
	}
}

// nsPath is the namespace a declaration goes in: its parent's path.
func nsPath(n *resolve.Node) []string {
	p := n.Path()
	segs := strings.Split(p, ".")
	return segs[:len(segs)-1]
}

func docComment(n *resolve.Node) string {
	var lines []string
	for _, s := range n.Docs {
		for _, l := range strings.Split(s.N.Text(), "\n") {
			l = strings.TrimSpace(l)
			if strings.HasPrefix(l, "///") {
				lines = append(lines, strings.TrimSpace(strings.TrimPrefix(l, "///")))
			}
		}
	}
	if len(lines) == 0 {
		return ""
	}
	return "/** " + strings.Join(lines, " ") + " */\n"
}

func (g *tsGen) enum(n *resolve.Node) string {
	var vs []string
	for _, v := range n.Children {
		vs = append(vs, fmt.Sprintf("%q", v.Name))
	}
	if len(vs) == 0 {
		vs = []string{"never"}
	}
	return docComment(n) + fmt.Sprintf("export type %s = %s;", n.Name, strings.Join(vs, " | "))
}

func (g *tsGen) record(n *resolve.Node) string {
	var b strings.Builder
	b.WriteString(docComment(n))
	if p := g.c.ErrorParent(n); p != nil {
		fmt.Fprintf(&b, "export interface %s extends %s {\n", n.Name, p.Name)
	} else {
		fmt.Fprintf(&b, "export interface %s {\n", n.Name)
	}
	for _, m := range n.Children {
		if m.Decl.N == nil || m.Decl.N.Kind != syntax.Declare {
			continue
		}
		d := ast.Declare{N: m.Decl.N}
		if d.Params().N != nil {
			continue // a method
		}
		t, opt := g.tsType(d.Type(), m.Decl.Scope, m.Decl.File)
		q := ""
		if opt || d.Question() != nil {
			q = "?"
			t += " | null"
		}
		if doc := docComment(m); doc != "" {
			b.WriteString("  " + strings.TrimRight(doc, "\n") + "\n")
		}
		fmt.Fprintf(&b, "  %s%s: %s;\n", m.Name, q, t)
	}
	b.WriteString("}")
	return b.String()
}

// tsType maps a Heron type as written to TS; the bool reports `T?`.
func (g *tsGen) tsType(t ast.Type, sc *resolve.Scope, f *resolve.File) (string, bool) {
	switch t := t.(type) {
	case ast.NamedType:
		var args []string
		for _, a := range t.Args().Args() {
			if pa, ok := a.(ast.PositionalArg); ok {
				args = append(args, g.tsExpr(pa.Expr(), sc, f))
			}
		}
		return g.named(resolve.PathSegs(t.Path().N), t.Path().N, args, sc, f), false
	case ast.OptionalType:
		s, _ := g.tsType(t.Type(), sc, f)
		return s, true
	default:
	}
	return "unknown", false
}

func (g *tsGen) tsExpr(e ast.Expr, sc *resolve.Scope, f *resolve.File) string {
	switch e := e.(type) {
	case ast.PathExpr:
		return g.named(resolve.PathSegs(e.Path().N), e.N, nil, sc, f)
	case ast.CallExpr:
		if p, ok := e.Callee().(ast.PathExpr); ok {
			var args []string
			for _, a := range e.Args().Args() {
				if pa, ok := a.(ast.PositionalArg); ok {
					args = append(args, g.tsExpr(pa.Expr(), sc, f))
				}
			}
			return g.named(resolve.PathSegs(p.Path().N), p.N, args, sc, f)
		}
	default:
	}
	return "unknown"
}

func arg(args []string, i int) string {
	if i < len(args) {
		return args[i]
	}
	return "unknown"
}

func (g *tsGen) named(segs []string, at *syntax.Node, args []string, sc *resolve.Scope, f *resolve.File) string {
	n := lookupWhere(sc, f, at, segs, func(n *resolve.Node) bool { return resolve.IsBuiltin(n) || g.c.IsType(n) || g.c.IsEnum(n) })
	if n == nil {
		return "unknown"
	}
	if resolve.IsBuiltin(n) || n.Decl.File == nil || n.Decl.File.ID.IsStd() {
		switch n.Name {
		case "String":
			return "string"
		case "Bool":
			return "boolean"
		case "Int", "Float":
			return "number"
		case "Decimal":
			return "Decimal"
		case "Bytes":
			return "Uint8Array"
		case "Null":
			return "null"
		case "Prose":
			return "MdastRoot"
		case "List":
			return "Array<" + arg(args, 0) + ">"
		case "Set":
			return "Set<" + arg(args, 0) + ">"
		case "Map":
			return "Map<" + arg(args, 0) + ", " + arg(args, 1) + ">"
		case "Ref":
			return "Ref"
		case "Timestamp", "Time":
			return "Date"
		case "Duration":
			return "Duration"
		case "Money":
			return "{ amount: Decimal; currency: string }"
		case "Stream":
			return "AsyncIterable<" + arg(args, 0) + ">"
		}
		return "unknown"
	}
	return n.Path()
}

// lookupWhere resolves a path, taking the first binding that pred accepts.
func lookupWhere(sc *resolve.Scope, f *resolve.File, at *syntax.Node, segs []string, pred func(*resolve.Node) bool) *resolve.Node {
	if sc == nil || len(segs) == 0 {
		return nil
	}
	start, _ := at.Span()
	var out *resolve.Node
	sc.Each(segs[0], f, start, func(b resolve.Binding) bool {
		n := b.Node
		for _, s := range segs[1:] {
			if n == nil {
				break
			}
			n = n.Child(s)
		}
		if n != nil && pred(n) {
			out = n
			return false
		}
		return true
	})
	return out
}
