// TS writes `.heron/types.ts`, the TS types of every type and enum the
// project and its packages declare, and `.heron/bindings.ts`, whose `bind`
// wraps each implementation with the signature of the declaration it's
// bound to, so `tsc` checks implementations against Heron, as the Interop
// tab's `heron gen ts` does.
func TS(in *Input) ([]registry.GeneratedFile, error) {
	g := &tsGen{c: in.Checker}
	trees := []*resolve.Tree{in.Tree}
	seen := map[*resolve.Package]bool{}
	var pkgs func(*resolve.Tree)
	pkgs = func(t *resolve.Tree) {
		for _, p := range t.Imports {
			if seen[p] || p.Tree == nil {
				continue
			}
			seen[p] = true
			if p.Tree.Entry == nil || !p.Tree.Entry.ID.IsStd() {
				trees = append(trees, p.Tree)
			}
			pkgs(p.Tree)
		}
	}
	pkgs(in.Tree)
	root := &tsNS{children: map[string]*tsNS{}}
	for _, t := range trees {
		t.Walk(func(n *resolve.Node) {
			if n.Shape == resolve.ShapeMounted || n.Decl.N == nil {
				return
			}
			switch {
			case g.c.IsEnum(n) && n.Name != "":
				root.at(nsPath(n)).decls = append(root.at(nsPath(n)).decls, g.enum(n))
			case g.c.IsType(n) && n.Name != "" && types.IsStd(g.c.KindOf(n), "types", "types.type"):
				root.at(nsPath(n)).decls = append(root.at(nsPath(n)).decls, g.record(n))
			}
		})
	}
	var b strings.Builder
	b.WriteString("// Code generated by `heron generate ts` from the Heron tree. DO NOT EDIT.\n")
	b.WriteString("import type { Decimal, Duration, MdastRoot, Ref } from \"@heron/runtime\";\n\n")
	root.write(&b, "", true)

	g.prefix = "T."
	disc := extension.Discover(in.Tree, in.Checker)
	binds := &tsNS{children: map[string]*tsNS{}}
	for _, s := range disc.Specs {
		if s.Name != extension.JSHost {
			continue
		}
		for _, d := range s.Decls {
			if d.Point == protocol.PointRenderer {
				// A renderer module names its kinds itself, with
				// defineRenderer; there is nothing to bind.
				continue
			}
			segs := strings.Split(d.Path, ".")
			ns := binds.at(segs[:len(segs)-1])
			ns.decls = append(ns.decls, g.binding(d, segs[len(segs)-1]))
		}
	}
	var bb strings.Builder
	bb.WriteString("// Code generated by `heron generate ts` from the Heron tree. DO NOT EDIT.\n")
	bb.WriteString("import { defineFunc, defineGenerator, defineLint, defineMacro, defineResource, defineTransport, stamp } from \"@heron/runtime\";\n")
	bb.WriteString("import type { Ctx, FuncImpl, GeneratorImpl, LintImpl, MacroImpl, ResourceDriver, ResourceImpl, Transport, TransportImpl } from \"@heron/runtime\";\n")
	bb.WriteString("import type * as T from \"./types.ts\";\n\n")
	bb.WriteString("/** Binds an implementation to its Heron declaration, by the declaration's path. */\n")
	bb.WriteString("export const bind = ")
	binds.writeObject(&bb, "")
	bb.WriteString(";\n")
	return []registry.GeneratedFile{
		{Path: ".heron/types.ts", Content: []byte(b.String()), Ignored: true},
		{Path: ".heron/bindings.ts", Content: []byte(bb.String()), Ignored: true},
	}, nil
}

type tsGen struct {
	c      *types.Checker
	prefix string // before a declared type's path: "" in types.ts, "T." in bindings.ts
}

// tsNS is a namespace of types.ts or an object of bindings.ts.
type tsNS struct {
	children map[string]*tsNS
	decls    []string
}

func (ns *tsNS) at(segs []string) *tsNS {
	for _, s := range segs {
		c := ns.children[s]
		if c == nil {
			c = &tsNS{children: map[string]*tsNS{}}
			ns.children[s] = c
		}
		ns = c
	}
	return ns
}

func (ns *tsNS) write(b *strings.Builder, indent string, top bool) {
	for _, d := range ns.decls {
		for _, l := range strings.Split(strings.TrimRight(d, "\n"), "\n") {
			b.WriteString(indent + l + "\n")
		}
		b.WriteString("\n")
	}
	names := make([]string, 0, len(ns.children))
	for k := range ns.children {
		names = append(names, k)
	}
	sort.Strings(names)
	for _, k := range names {
		kw := "export namespace"
		if top {
			kw = "export declare namespace"
		}
		fmt.Fprintf(b, "%s%s %s {\n", indent, kw, k)
		ns.children[k].write(b, indent+"  ", false)
		fmt.Fprintf(b, "%s}\n\n", indent)
	}
}

func (ns *tsNS) writeObject(b *strings.Builder, indent string) {
	b.WriteString("{\n")
	for _, d := range ns.decls {
		for _, l := range strings.Split(strings.TrimRight(d, "\n"), "\n") {
			b.WriteString(indent + "  " + l + "\n")
		}
	}
	names := make([]string, 0, len(ns.children))
	for k := range ns.children {
		names = append(names, k)
	}
	sort.Strings(names)
	for _, k := range names {
		fmt.Fprintf(b, "%s  %s: ", indent, k)
		ns.children[k].writeObject(b, indent+"  ")
		b.WriteString(",\n")
	}
	b.WriteString(indent + "}")
}

// nsPath is the namespace a declaration goes in: its parent's path.
func nsPath(n *resolve.Node) []string {
	p := n.Path()
	segs := strings.Split(p, ".")
	return segs[:len(segs)-1]
}

func docComment(n *resolve.Node) string {
	var lines []string
	for _, s := range n.Docs {
		for _, l := range strings.Split(s.N.Text(), "\n") {
			l = strings.TrimSpace(l)
			if strings.HasPrefix(l, "///") {
				lines = append(lines, strings.TrimSpace(strings.TrimPrefix(l, "///")))
			}
		}
	}
	if len(lines) == 0 {
		return ""
	}
	return "/** " + strings.Join(lines, " ") + " */\n"
}

func (g *tsGen) enum(n *resolve.Node) string {
	var vs []string
	for _, v := range n.Children {
		vs = append(vs, fmt.Sprintf("%q", v.Name))
	}
	if len(vs) == 0 {
		vs = []string{"never"}
	}
	return docComment(n) + fmt.Sprintf("export type %s = %s;", n.Name, strings.Join(vs, " | "))
}

func (g *tsGen) record(n *resolve.Node) string {
	var b strings.Builder
	b.WriteString(docComment(n))
	fmt.Fprintf(&b, "export interface %s {\n", n.Name)
	for _, m := range n.Children {
		if m.Decl.N == nil || m.Decl.N.Kind != syntax.Declare {
			continue
		}
		d := ast.Declare{N: m.Decl.N}
		if d.Params().N != nil {
			continue // a method
		}
		t, opt := g.tsType(d.Type(), m.Decl.Scope, m.Decl.File)
		q := ""
		if opt || d.Question() != nil {
			q = "?"
			t += " | null"
		}
		if doc := docComment(m); doc != "" {
			b.WriteString("  " + strings.TrimRight(doc, "\n") + "\n")
		}
		fmt.Fprintf(&b, "  %s%s: %s;\n", m.Name, q, t)
	}
	b.WriteString("}")
	return b.String()
}

// tsType maps a Heron type as written to TS, as the Interop tab's table
// does; the bool reports `T?`.
func (g *tsGen) tsType(t ast.Type, sc *resolve.Scope, f *resolve.File) (string, bool) {
	switch t := t.(type) {
	case ast.NamedType:
		var args []string
		for _, a := range t.Args().Args() {
			if pa, ok := a.(ast.PositionalArg); ok {
				args = append(args, g.tsExpr(pa.Expr(), sc, f))
			}
		}
		return g.named(resolve.PathSegs(t.Path().N), t.Path().N, args, sc, f), false
	case ast.OptionalType:
		s, _ := g.tsType(t.Type(), sc, f)
		return s, true
	default:
	}
	return "unknown", false
}

func (g *tsGen) tsExpr(e ast.Expr, sc *resolve.Scope, f *resolve.File) string {
	switch e := e.(type) {
	case ast.PathExpr:
		return g.named(resolve.PathSegs(e.Path().N), e.N, nil, sc, f)
	case ast.CallExpr:
		if p, ok := e.Callee().(ast.PathExpr); ok {
			var args []string
			for _, a := range e.Args().Args() {
				if pa, ok := a.(ast.PositionalArg); ok {
					args = append(args, g.tsExpr(pa.Expr(), sc, f))
				}
			}
			return g.named(resolve.PathSegs(p.Path().N), p.N, args, sc, f)
		}
	default:
	}
	return "unknown"
}

func arg(args []string, i int) string {
	if i < len(args) {
		return args[i]
	}
	return "unknown"
}

func (g *tsGen) named(segs []string, at *syntax.Node, args []string, sc *resolve.Scope, f *resolve.File) string {
	n := extension.LookupWhere(sc, f, at, segs, func(n *resolve.Node) bool { return resolve.IsBuiltin(n) || g.c.IsType(n) || g.c.IsEnum(n) })
	if n == nil {
		return "unknown"
	}
	if resolve.IsBuiltin(n) || n.Decl.File == nil || n.Decl.File.ID.IsStd() {
		switch n.Name {
		case "String":
			return "string"
		case "Bool":
			return "boolean"
		case "Int", "Float":
			return "number"
		case "Decimal":
			return "Decimal"
		case "Bytes":
			return "Uint8Array"
		case "Null":
			return "null"
		case "Prose":
			return "MdastRoot"
		case "List":
			return "Array<" + arg(args, 0) + ">"
		case "Set":
			return "Set<" + arg(args, 0) + ">"
		case "Map":
			return "Map<" + arg(args, 0) + ", " + arg(args, 1) + ">"
		case "Ref":
			return "Ref"
		case "Timestamp", "Time":
			return "Date"
		case "Duration":
			return "Duration"
		case "Money":
			return "{ amount: Decimal; currency: string }"
		case "Stream":
			return "AsyncIterable<" + arg(args, 0) + ">"
		}
		return "unknown"
	}
	return g.prefix + n.Path()
}

// binding writes one member of `bind`.
func (g *tsGen) binding(d extension.Decl, name string) string {
	n := d.Node
	doc := docComment(n)
	argsT, resT := "Record<string, never>", "unknown"
	var parts []string
	var ps ast.Params
	var slot ast.Type
	switch n.Decl.N.Kind {
	case syntax.Declare:
		ps, slot = ast.Declare{N: n.Decl.N}.Params(), ast.Declare{N: n.Decl.N}.Type()
	case syntax.Value:
		ps, slot = ast.Value{N: n.Decl.N}.Params(), ast.Value{N: n.Decl.N}.Type()
	}
	sc := n.Body
	if sc == nil {
		sc = n.Decl.Scope
	}
	for _, p := range ps.Params() {
		if p.Ident() == nil {
			continue
		}
		t, opt := g.tsType(p.Type(), sc, n.Decl.File)
		q := ""
		if opt || p.Question() != nil || p.Default() != nil {
			q = "?"
		}
		parts = append(parts, fmt.Sprintf("%s%s: %s", p.Ident().Text, q, t))
	}
	if len(parts) > 0 {
		argsT = "{ " + strings.Join(parts, "; ") + " }"
	}
	if nt, ok := slot.(ast.NamedType); ok {
		for _, a := range nt.Args().Args() {
			if pa, ok := a.(ast.PositionalArg); ok {
				resT = g.tsExpr(pa.Expr(), n.Decl.Scope, n.Decl.File)
			}
		}
	}
	path := fmt.Sprintf("%q", d.Path)
	var body string
	switch d.Point {
	case protocol.PointFunc:
		if resT == "unknown" && slot != nil {
			resT = "void"
		}
		body = fmt.Sprintf("%s: (fn: (args: %s, ctx: Ctx) => %s | Promise<%s>): FuncImpl<%s, %s> => stamp(defineFunc(fn), %s),", name, argsT, resT, resT, argsT, resT, path)
	case protocol.PointMacro:
		body = fmt.Sprintf("%s: (expand: (args: %s, ctx: Ctx) => string | Promise<string>): MacroImpl<%s> => stamp(defineMacro(expand), %s),", name, argsT, argsT, path)
	case protocol.PointTransport:
		body = fmt.Sprintf("%s: (t: Transport): TransportImpl => stamp(defineTransport(t), %s),", name, path)
	case protocol.PointLint:
		body = fmt.Sprintf("%s: (l: { run: LintImpl[\"run\"] }): LintImpl => stamp(defineLint(l), %s),", name, path)
	case protocol.PointResource:
		body = fmt.Sprintf("%s: (d: ResourceDriver<%s>): ResourceImpl<%s> => stamp(defineResource(d), %s),", name, resT, resT, path)
	case protocol.PointGenerator:
		body = fmt.Sprintf("%s: (g: { generate: GeneratorImpl[\"generate\"] }): GeneratorImpl => stamp(defineGenerator({ target: %q, ...g }), %s),", name, d.Target, path)
	}
	return doc + body
}
