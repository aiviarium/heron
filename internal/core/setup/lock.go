// LockFile is the lock's name at the project's root.
const LockFile = "heron.lock"

// Lock is heron.lock: the packages a tree imports, pinned by version and
// checksum, and the sources its projects name, pinned by commit. The file
// is Heron, as on the Example tab:
//
//	packages.{
//	  "std/spec" = { version = "1.0", checksum = "sha256:…" }
//	}
//
//	sources.{
//	  mailer = { url = "https://…", ref = "v1.8.0", commit = "3c8e5b1…" }
//	}
//
//	tools.{
//	  vale = { version = "v3.28.1", checksum = "sha256:…" }
//	}
type Lock struct {
	Packages map[string]Pin
	Sources  map[string]SourcePin
	// Tools are pinned by the setup steps units register, such as Vale.
	Tools map[string]registry.ToolPin
}

// Pin pins a package. A package from git also pins the repository, the
// package's folder in it, and the tag and commit it was installed from.
type Pin struct {
	Version, Checksum string
	URL, Path, Ref    string
	Commit            string
}

// Git reports whether the pin is of a package installed from git.
func (p Pin) Git() bool { return p.URL != "" }

// SourcePin pins a source.
type SourcePin struct{ URL, Ref, Commit string }

// ReadLock reads a lock; a file that doesn't exist is an empty lock.
func ReadLock(file string) (*Lock, error) {
	l := &Lock{Packages: map[string]Pin{}, Sources: map[string]SourcePin{}, Tools: map[string]registry.ToolPin{}}
	if _, err := os.Stat(file); errors.Is(err, os.ErrNotExist) {
		return l, nil
	}
	id, err := resolve.Canonical(file)
	if err != nil {
		return nil, err
	}
	res := check.NewSession().Check(id)
	if res.Diags.HasErrors() {
		for _, d := range res.Diags {
			return nil, fmt.Errorf("%s doesn't check: %s", file, d.Message)
		}
	}
	m := eval.New(res.Tree, res.Checker, registry.New(), eval.Caps{})
	entries := func(name string) (map[string]map[string]any, error) {
		out := map[string]map[string]any{}
		n := res.Tree.Find(name)
		if n == nil {
			return out, nil
		}
		for _, c := range n.Children {
			v, err := m.Value(context.Background(), c)
			if err != nil {
				return nil, fmt.Errorf("%s: %s.%s: %w", file, name, c.Name, err)
			}
			fields, ok := eval.Plain(v).(map[string]any)
			if !ok {
				return nil, fmt.Errorf("%s: %s.%s isn't a map", file, name, c.Name)
			}
			out[c.Name] = fields
		}
		return out, nil
	}
	pkgs, err := entries("packages")
	if err != nil {
		return nil, err
	}
	for k, f := range pkgs {
		l.Packages[k] = Pin{Version: str(f["version"]), Checksum: str(f["checksum"]),
			URL: str(f["url"]), Path: str(f["path"]), Ref: str(f["ref"]), Commit: str(f["commit"])}
	}
	srcs, err := entries("sources")
	if err != nil {
		return nil, err
	}
	for k, f := range srcs {
		l.Sources[k] = SourcePin{URL: str(f["url"]), Ref: str(f["ref"]), Commit: str(f["commit"])}
	}
	tools, err := entries("tools")
	if err != nil {
		return nil, err
	}
	for k, f := range tools {
		l.Tools[k] = registry.ToolPin{Version: str(f["version"]), Checksum: str(f["checksum"])}
	}
	return l, nil
}

func str(v any) string {
	s, _ := v.(string)
	return s
}

var identRE = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

func key(k string) string {
	if identRE.MatchString(k) {
		return k
	}
	return strconv.Quote(k)
}

// Format writes the lock as heron fmt would, keys sorted.
func (l *Lock) Format() string {
	var b strings.Builder
	b.WriteString("// Generated by `heron run setup`: the packages this tree imports and the\n")
	b.WriteString("// sources its projects name, pinned. Commit it.\n")
	blocks := 0
	if len(l.Packages) > 0 {
		b.WriteString("packages.{\n")
		for _, k := range sortedKeys(l.Packages) {
			p := l.Packages[k]
			fmt.Fprintf(&b, "  %s = { version = %s, checksum = %s", key(k), strconv.Quote(p.Version), strconv.Quote(p.Checksum))
			if p.Git() {
				fmt.Fprintf(&b, ", url = %s", strconv.Quote(p.URL))
				if p.Path != "" {
					fmt.Fprintf(&b, ", path = %s", strconv.Quote(p.Path))
				}
				fmt.Fprintf(&b, ", ref = %s, commit = %s", strconv.Quote(p.Ref), strconv.Quote(p.Commit))
			}
			b.WriteString(" }\n")
		}
		b.WriteString("}\n")
		blocks++
	}
	if len(l.Sources) > 0 {
		if blocks > 0 {
			b.WriteString("\n")
		}
		b.WriteString("sources.{\n")
		for _, k := range sortedKeys(l.Sources) {
			s := l.Sources[k]
			fmt.Fprintf(&b, "  %s = { url = %s", key(k), strconv.Quote(s.URL))
			if s.Ref != "" {
				fmt.Fprintf(&b, ", ref = %s", strconv.Quote(s.Ref))
			}
			fmt.Fprintf(&b, ", commit = %s }\n", strconv.Quote(s.Commit))
		}
		b.WriteString("}\n")
		blocks++
	}
	if len(l.Tools) > 0 {
		if blocks > 0 {
			b.WriteString("\n")
		}
		b.WriteString("tools.{\n")
		for _, k := range sortedKeys(l.Tools) {
			t := l.Tools[k]
			fmt.Fprintf(&b, "  %s = { version = %s, checksum = %s }\n", key(k), strconv.Quote(t.Version), strconv.Quote(t.Checksum))
		}
		b.WriteString("}\n")
	}
	return b.String()
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// packagePins returns the pin of every versioned package the tree imports,
// from the copy this heron resolved: the embedded standard packages or a
// package directory.
func packagePins(t *resolve.Tree) map[string]Pin {
	out := map[string]Pin{}
	for _, p := range t.Imports {
		// A file import has no major version; a git import's may be 0,
		// as in `…//heron@v0`.
		if (p.Major == 0 && p.Git == nil) || p.Tree == nil || p.Tree.Entry == nil {
			continue
		}
		if p.Git != nil {
			// The checksum covers every file of the installed folder.
			sum, err := DirChecksum(filepath.Dir(string(p.Tree.Entry.ID)))
			if err != nil {
				sum = ""
			}
			out[p.Name] = Pin{Version: p.Version, Checksum: sum, URL: p.Git.URL, Path: p.Git.Path}
			continue
		}
		out[p.Name] = Pin{Version: p.Version, Checksum: checksum(p.Tree)}
	}
	return out
}

// checksum hashes a package's files by their paths inside the package and
// their content, so it is the same wherever the package is read from.
func checksum(t *resolve.Tree) string {
	base := path.Dir(string(t.Entry.ID))
	type f struct{ rel, src string }
	var files []f
	for _, x := range t.Files {
		files = append(files, f{strings.TrimPrefix(string(x.ID), base+"/"), x.Src})
	}
	sort.Slice(files, func(i, j int) bool { return files[i].rel < files[j].rel })
	h := sha256.New()
	for _, x := range files {
		fmt.Fprintf(h, "%s\x00%d\x00%s", x.rel, len(x.src), x.src)
	}
	return "sha256:" + hex.EncodeToString(h.Sum(nil))
}

// source is a project with a source, checked out at its path.
type source struct {
	name string // the project's path in the tree, the lock's key
	url  string
	ref  string
	dir  string // relative to the root, slash-separated
}

// sources finds the projects of the tree that name a source.
func sources(ctx context.Context, m *eval.Machine) ([]source, error) {
	var out []source
	var err error
	m.Tree.Walk(func(n *resolve.Node) {
		if err != nil {
			return
		}
		k := m.Types.KindOf(n)
		if k == nil || !types.IsStd(k, "spec", "spec.project") {
			return
		}
		c := n.Child("source")
		if c == nil {
			return
		}
		v, e := m.Value(ctx, c)
		if e != nil {
			err = e
			return
		}
		fields, _ := eval.Plain(v).(map[string]any)
		s := source{name: n.Path(), url: str(fields["url"]), ref: str(fields["ref"])}
		p, ok, e := m.KindArg(ctx, n, "path")
		if e != nil {
			err = e
			return
		}
		s.dir, _ = p.(string)
		if !ok || s.url == "" || s.dir == "" || s.dir == "." {
			err = fail("%s names a source but no url, or no path of its own to check it out at", s.name)
			return
		}
		out = append(out, s)
	})
	sort.Slice(out, func(i, j int) bool { return out[i].name < out[j].name })
	return out, err
}

var shaRE = regexp.MustCompile(`^[0-9a-f]{40}$`)

// resolveRef finds the commit a ref names at a url.
func resolveRef(ctx context.Context, m *eval.Machine, url, ref string) (string, error) {
	if shaRE.MatchString(ref) {
		return ref, nil
	}
	want := ref
	if want == "" {
		want = "HEAD"
	}
	// An annotated tag lists its own object and, peeled, the commit.
	exit, err := run(ctx, m, m.Dir, "git", "ls-remote", url, want, want+"^{}")
	if err != nil || exit.Code != 0 {
		return "", fail("can't read %s: %s", url, failure(exit, err))
	}
	commit := ""
	for _, line := range strings.Split(string(exit.Stdout), "\n") {
		f := strings.Fields(line)
		if len(f) != 2 {
			continue
		}
		if strings.HasSuffix(f[1], "^{}") || commit == "" {
			commit = f[0] // a peeled tag names the commit itself
		}
	}
	if commit == "" {
		return "", fail("%s has no ref %s", url, want)
	}
	return commit, nil
}

// checkout puts a source's commit at its path; it reports whether it
// changed anything.
func checkout(ctx context.Context, m *eval.Machine, s source, commit string) (bool, error) {
	dir := filepath.Join(m.Dir, filepath.FromSlash(s.dir))
	if st, err := os.Stat(dir); err == nil && st.IsDir() {
		if exit, err := run(ctx, m, dir, "git", "rev-parse", "HEAD"); err == nil && exit.Code == 0 {
			if strings.TrimSpace(string(exit.Stdout)) == commit {
				return false, nil
			}
			if exit, err := run(ctx, m, dir, "git", "checkout", "-q", "--detach", commit); err == nil && exit.Code == 0 {
				return true, nil
			}
			if exit, err := run(ctx, m, dir, "git", "fetch", "-q", s.url); err != nil || exit.Code != 0 {
				return false, fail("can't fetch %s into %s: %s", s.url, s.dir, failure(exit, err))
			}
			if exit, err := run(ctx, m, dir, "git", "checkout", "-q", "--detach", commit); err != nil || exit.Code != 0 {
				return false, fail("can't check out %s in %s: %s", commit, s.dir, failure(exit, err))
			}
			return true, nil
		}
		if ents, _ := os.ReadDir(dir); len(ents) > 0 {
			return false, fail("%s exists and isn't a checkout of %s; move it away to set up %s", s.dir, s.url, s.name)
		}
	}
	if exit, err := run(ctx, m, m.Dir, "git", "clone", "-q", "--no-checkout", s.url, dir); err != nil || exit.Code != 0 {
		return false, fail("can't clone %s: %s", s.url, failure(exit, err))
	}
	if exit, err := run(ctx, m, dir, "git", "checkout", "-q", "--detach", commit); err != nil || exit.Code != 0 {
		return false, fail("can't check out %s in %s: %s", commit, s.dir, failure(exit, err))
	}
	return true, nil
}

func installPackages(ctx context.Context, c *registry.FuncCall, r *registry.Registry) (any, error) {
	m, err := machine(ctx)
	if err != nil {
		return nil, err
	}
	update, _ := c.Args["update"].(bool)
	file := filepath.Join(m.Dir, LockFile)
	old, err := ReadLock(file)
	if err != nil {
		return nil, fail("%v", err)
	}
	lock := &Lock{Packages: map[string]Pin{}, Sources: map[string]SourcePin{}, Tools: map[string]registry.ToolPin{}}
	pkgs := map[string]any{}
	for name, have := range packagePins(m.Tree) {
		pin, pinned := old.Packages[name]
		if have.Git() {
			// Installed from git before the tree checked, from the pin.
			if !pinned || pin.URL != have.URL || pin.Path != have.Path {
				return nil, fail("heron.lock doesn't pin %s from %s; run heron run setup to pin and install it", name, have.URL)
			}
			if pin.Checksum != have.Checksum {
				return nil, fail("heron.lock pins %s at %s (%s), but .heron/packages has %s; run heron run setup to install it again",
					name, pin.Commit, pin.Checksum, have.Checksum)
			}
			have.Ref, have.Commit = pin.Ref, pin.Commit
			switch {
			case pin.Version == "":
				pkgs[name] = "pinned " + have.Version
			case pin.Version != have.Version:
				pkgs[name] = fmt.Sprintf("moved %s to %s", pin.Version, have.Version)
			default:
				pkgs[name] = "ok " + have.Version
			}
			lock.Packages[name] = have
			continue
		}
		switch {
		case !pinned:
			pkgs[name] = "pinned " + have.Version
		case pin == have:
			pkgs[name] = "ok " + have.Version
		case update:
			pkgs[name] = fmt.Sprintf("moved %s to %s", pin.Version, have.Version)
		default:
			return nil, fail("heron.lock pins %s %s (%s), but this heron has %s (%s); update heron, or run setup with --update to move the pin",
				name, pin.Version, pin.Checksum, have.Version, have.Checksum)
		}
		lock.Packages[name] = have
	}
	srcs, err := sources(ctx, m)
	if err != nil {
		return nil, err
	}
	out := map[string]any{}
	for _, s := range srcs {
		pin, ok := old.Sources[s.name]
		state := "ok"
		if !ok || pin.URL != s.url || pin.Ref != s.ref || pin.Commit == "" {
			// A new source, or one whose url or ref changed, is pinned again.
			commit, err := resolveRef(ctx, m, s.url, s.ref)
			if err != nil {
				return nil, err
			}
			pin, state = SourcePin{URL: s.url, Ref: s.ref, Commit: commit}, "pinned"
		}
		changed, err := checkout(ctx, m, s, pin.Commit)
		if err != nil {
			return nil, err
		}
		if changed && state == "ok" {
			state = "checked out"
		}
		lock.Sources[s.name] = pin
		out[s.name] = map[string]any{"path": s.dir, "commit": pin.Commit, "state": state}
	}
	tools := map[string]any{}
	for _, st := range r.SetupSteps() {
		var was *registry.ToolPin
		if p, ok := old.Tools[st.Name]; ok {
			was = &p
		}
		pin, res, err := st.Run(ctx, m.Dir, was, update)
		if err != nil {
			return nil, fail("%s: %v", st.Name, err)
		}
		if pin != nil {
			lock.Tools[st.Name] = *pin
		}
		if res != nil {
			tools[st.Name] = res
		}
	}
	text := lock.Format()
	lockState := "unchanged"
	if b, err := os.ReadFile(file); err != nil || string(b) != text {
		if err := os.WriteFile(file, []byte(text), 0o644); err != nil {
			return nil, err
		}
		lockState = "written"
	}
	res := map[string]any{"packages": pkgs, "sources": out, "lock": lockState}
	if len(tools) > 0 {
		res["tools"] = tools
	}
	return res, nil
}

// generate runs every generation target, as `heron generate` without
// targets does, then writes setup's section of the managed ignore block. It
// returns the paths it wrote, relative to the root.
func generate(ctx context.Context, r *registry.Registry, o Options) (any, error) {
	m, err := machine(ctx)
	if err != nil {
		return nil, err
	}
	written := []any{}
	out, err := gen.Run(ctx, r, &gen.Input{Tree: m.Tree, Checker: m.Types, Dir: m.Dir}, nil)
	if out != nil {
		for _, w := range out.Written {
			written = append(written, w)
		}
	}
	if err != nil {
		return nil, fail("%v", err)
	}
	entries := []string{"/.heron/"}
	srcs, err := sources(ctx, m)
	if err != nil {
		return nil, err
	}
	for _, s := range srcs {
		entries = append(entries, "/"+strings.Trim(s.dir, "/")+"/")
	}
	changed, err := o.Ignore.WriteIgnore(m.Dir, entries)
	if err != nil {
		return nil, err
	}
	if changed {
		written = append(written, ".gitignore")
	}
	return written, nil
}
