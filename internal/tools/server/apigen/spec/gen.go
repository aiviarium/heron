const header = "Code generated by apigen from the server's API in Heron. DO NOT EDIT."

var initialisms = map[string]bool{"id": true, "html": true, "json": true, "url": true}

func words(s string) []string {
	return strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '.' })
}

func goName(s string) string {
	var b strings.Builder
	for _, w := range words(s) {
		if initialisms[w] {
			b.WriteString(strings.ToUpper(w))
		} else {
			b.WriteString(strings.ToUpper(w[:1]) + w[1:])
		}
	}
	return b.String()
}

func tsName(s string) string {
	var b strings.Builder
	for i, w := range words(s) {
		if i == 0 {
			b.WriteString(w)
		} else {
			b.WriteString(strings.ToUpper(w[:1]) + w[1:])
		}
	}
	return b.String()
}

func (a *API) isRecord(name string) bool {
	for _, r := range a.Records {
		if r.Name == name {
			return true
		}
	}
	return false
}

func goType(t Type) string {
	switch t.Name {
	case "String":
		return "string"
	case "Int":
		return "int64"
	case "Float":
		return "float64"
	case "Bool":
		return "bool"
	case "Any":
		return "any"
	case "List":
		return "[]" + goType(t.Args[0])
	case "Map":
		return "map[string]" + goType(t.Args[len(t.Args)-1])
	}
	return t.Name
}

func goFieldType(t Type) string {
	g := goType(t)
	if t.Optional && !strings.HasPrefix(g, "[]") && !strings.HasPrefix(g, "map[") && g != "any" {
		return "*" + g
	}
	return g
}

// goResult is the Go type an op's handler returns.
func (a *API) goResult(t *Type) string {
	if t == nil {
		return "struct{}"
	}
	if a.isRecord(t.Name) {
		return "*" + t.Name
	}
	return goType(*t)
}

func comment(b *bytes.Buffer, indent, doc string) {
	if doc != "" {
		fmt.Fprintf(b, "%s// %s\n", indent, doc)
	}
}

// Go writes the types, the Service interface and the routes of the API.
func Go(a *API, pkg string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\npackage %s\n\n", header, pkg)
	b.WriteString("import (\n\t\"context\"\n\t\"net/http\"\n\n\t\"github.com/aiviarium/heron/internal/tools/server/route\"\n)\n\n")
	b.WriteString("var (\n\t_ = context.Background\n\t_ = http.MethodGet\n)\n\n")
	for _, r := range a.Records {
		comment(&b, "", r.Doc)
		fmt.Fprintf(&b, "type %s struct {\n", r.Name)
		for _, f := range r.Fields {
			comment(&b, "\t", f.Doc)
			tag := f.Name
			if f.Type.Optional {
				tag += ",omitempty"
			}
			fmt.Fprintf(&b, "\t%s %s `json:%q`\n", goName(f.Name), goFieldType(f.Type), tag)
		}
		b.WriteString("}\n\n")
	}
	b.WriteString("// Service implements the ops.\ntype Service interface {\n")
	for _, op := range a.Ops {
		comment(&b, "\t", op.Doc)
		fmt.Fprintf(&b, "\t%s\n", a.goSig(op))
	}
	b.WriteString("}\n\n")
	b.WriteString("// Routes binds each op to its handler on s.\nfunc Routes(s Service) []route.Route {\n\treturn []route.Route{\n")
	for _, op := range a.Ops {
		fmt.Fprintf(&b, "\t\t{Op: %q, Method: %q, Path: %q, Stream: %v, Socket: %v, Handler: %s},\n",
			"spec_server."+op.Name, op.Method, op.Path, op.Stream() != nil, op.Socket, a.goHandler(op))
	}
	b.WriteString("\t}\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("formatting the Go output: %v", err)
	}
	return src, nil
}

func (a *API) goParamType(p Param) string {
	if a.isRecord(p.Type.Name) {
		return "*" + p.Type.Name
	}
	return goType(p.Type)
}

func (a *API) goSig(op *Op) string {
	name := goName(op.Name)
	if op.Socket {
		return name + "(w http.ResponseWriter, r *http.Request)"
	}
	ps := []string{"ctx context.Context"}
	for _, p := range op.Params {
		ps = append(ps, p.Name+" "+a.goParamType(p))
	}
	if el := op.Stream(); el != nil {
		elt := goType(*el)
		if a.isRecord(el.Name) {
			elt = "*" + el.Name
		}
		ps = append(ps, "send func("+elt+") error")
		return name + "(" + strings.Join(ps, ", ") + ") error"
	}
	return name + "(" + strings.Join(ps, ", ") + ") (" + a.goResult(op.Returns) + ", error)"
}

func (a *API) goHandler(op *Op) string {
	name := goName(op.Name)
	if op.Socket {
		return "func(w http.ResponseWriter, r *http.Request) { s." + name + "(w, r) }"
	}
	var b strings.Builder
	b.WriteString("func(w http.ResponseWriter, r *http.Request) {\n")
	args := []string{"r.Context()"}
	fail := "route.WriteError(w, err)"
	for _, p := range op.Params {
		v := "p_" + p.Name
		var src string
		switch p.In {
		case "query":
			src = "r.URL.Query().Get(" + fmt.Sprintf("%q", p.Name) + ")"
		case "path":
			src = "r.PathValue(" + fmt.Sprintf("%q", p.Name) + ")"
		case "header":
			src = "r.Header.Get(" + fmt.Sprintf("%q", p.Name) + ")"
		}
		switch {
		case p.In == "body" && a.isRecord(p.Type.Name):
			fmt.Fprintf(&b, "%s := &%s{}\nif err := route.DecodeBody(r, %s); err != nil {\n%s\nreturn\n}\n", v, p.Type.Name, v, fail)
		case p.In == "body":
			fmt.Fprintf(&b, "var %s %s\nif err := route.DecodeBody(r, &%s); err != nil {\n%s\nreturn\n}\n", v, goType(p.Type), v, fail)
		case p.Type.Name == "Int":
			fmt.Fprintf(&b, "%s, err := route.Int(%q, %s)\nif err != nil {\n%s\nreturn\n}\n", v, p.Name, src, fail)
		case p.Type.Name == "Bool":
			fmt.Fprintf(&b, "%s, err := route.Bool(%q, %s)\nif err != nil {\n%s\nreturn\n}\n", v, p.Name, src, fail)
		default:
			fmt.Fprintf(&b, "%s := %s\n", v, src)
		}
		args = append(args, v)
	}
	if op.Stream() != nil {
		b.WriteString("ev := route.NewEvents(w)\n")
		el := op.Stream()
		elt := goType(*el)
		if a.isRecord(el.Name) {
			elt = "*" + el.Name
		}
		args = append(args, "func(e "+elt+") error { return ev.Send(e) }")
		fmt.Fprintf(&b, "if err := s.%s(%s); err != nil {\nev.Fail(err)\n}\n}", name, strings.Join(args, ", "))
		return b.String()
	}
	fmt.Fprintf(&b, "out, err := s.%s(%s)\nif err != nil {\n%s\nreturn\n}\nroute.WriteJSON(w, out)\n}", name, strings.Join(args, ", "), fail)
	return b.String()
}

