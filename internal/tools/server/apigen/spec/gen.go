func tsType(t Type) string {
	switch t.Name {
	case "String":
		return "string"
	case "Int", "Float":
		return "number"
	case "Bool":
		return "boolean"
	case "Any":
		return "unknown"
	case "List":
		return tsType(t.Args[0]) + "[]"
	case "Map":
		return "{ [key: string]: " + tsType(t.Args[len(t.Args)-1]) + " }"
	case "Stream":
		return "AsyncIterable<" + tsType(t.Args[0]) + ">"
	}
	return t.Name
}

const tsRuntime = `export class ApiError extends Error {
  constructor(readonly status: number, message: string) {
    super(message);
  }
}

export interface RouteInfo {
  op: string;
  method: string;
  path: string;
  stream: boolean;
  socket: boolean;
}

type Fetch = typeof fetch;

async function call<T>(f: Fetch, base: string, method: string, path: string, body?: unknown): Promise<T> {
  const res = await f(base + path, {
    method,
    headers: body === undefined ? undefined : { "Content-Type": "application/json" },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  if (!res.ok) throw new ApiError(res.status, await errorText(res));
  return (await res.json()) as T;
}

async function errorText(res: Response): Promise<string> {
  try {
    const j = (await res.json()) as { error?: string };
    return j.error ?? res.statusText;
  } catch {
    return res.statusText;
  }
}

async function* events<T>(f: Fetch, base: string, method: string, path: string, body?: unknown, signal?: AbortSignal): AsyncIterable<T> {
  const res = await f(base + path, {
    method,
    headers: body === undefined ? undefined : { "Content-Type": "application/json" },
    body: body === undefined ? undefined : JSON.stringify(body),
    signal,
  });
  if (!res.ok || !res.body) throw new ApiError(res.status, await errorText(res));
  const reader = res.body.pipeThrough(new TextDecoderStream()).getReader();
  let buf = "";
  for (;;) {
    const { value, done } = await reader.read();
    if (done) return;
    buf += value;
    let i: number;
    while ((i = buf.indexOf("\n\n")) >= 0) {
      const chunk = buf.slice(0, i);
      buf = buf.slice(i + 2);
      let event = "message";
      let data = "";
      for (const line of chunk.split("\n")) {
        if (line.startsWith("event: ")) event = line.slice(7);
        else if (line.startsWith("data: ")) data += line.slice(6);
      }
      if (event === "error") throw new ApiError(500, (JSON.parse(data) as { error: string }).error);
      yield JSON.parse(data) as T;
    }
  }
}

function q(params: { [key: string]: string | number | boolean | undefined }): string {
  const s = new URLSearchParams();
  for (const [k, v] of Object.entries(params)) if (v !== undefined) s.set(k, String(v));
  const out = s.toString();
  return out ? "?" + out : "";
}

void q;
void events;
void call;
`

// TS writes the types and the client of the API.
func TS(a *API) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\n", header)
	for _, r := range a.Records {
		if r.Doc != "" {
			fmt.Fprintf(&b, "/** %s */\n", r.Doc)
		}
		fmt.Fprintf(&b, "export interface %s {\n", r.Name)
		for _, f := range r.Fields {
			if f.Doc != "" {
				fmt.Fprintf(&b, "  /** %s */\n", f.Doc)
			}
			opt := ""
			if f.Type.Optional {
				opt = "?"
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", f.Name, opt, tsType(f.Type))
		}
		b.WriteString("}\n\n")
	}
	b.WriteString(tsRuntime)
	b.WriteString("\nexport const routes: RouteInfo[] = [\n")
	for _, op := range a.Ops {
		fmt.Fprintf(&b, "  { op: %q, method: %q, path: %q, stream: %v, socket: %v },\n",
			"spec_server."+op.Name, op.Method, op.Path, op.Stream() != nil, op.Socket)
	}
	b.WriteString("];\n\nexport interface Client {\n")
	for _, op := range a.Ops {
		if op.Doc != "" {
			fmt.Fprintf(&b, "  /** %s */\n", op.Doc)
		}
		fmt.Fprintf(&b, "  %s;\n", a.tsSig(op))
	}
	b.WriteString("}\n\n/** The client; base is the server's origin, empty for the page's own. */\n")
	b.WriteString("export function createClient(base = \"\", f: Fetch = (...a) => fetch(...a)): Client {\n  return {\n")
	for _, op := range a.Ops {
		fmt.Fprintf(&b, "    %s,\n", a.tsImpl(op))
	}
	b.WriteString("  };\n}\n")
	return b.Bytes()
}

func (a *API) tsParams(op *Op) []string {
	var ps []string
	for _, p := range op.Params {
		ps = append(ps, tsName(p.Name)+": "+tsType(p.Type))
	}
	return ps
}

func (a *API) tsSig(op *Op) string {
	name := tsName(op.Name)
	if op.Socket {
		return name + "(): string"
	}
	ps := a.tsParams(op)
	if el := op.Stream(); el != nil {
		ps = append(ps, "signal?: AbortSignal")
		return name + "(" + strings.Join(ps, ", ") + "): AsyncIterable<" + tsType(*el) + ">"
	}
	ret := "void"
	if op.Returns != nil {
		ret = tsType(*op.Returns)
	}
	return name + "(" + strings.Join(ps, ", ") + "): Promise<" + ret + ">"
}

func (a *API) tsImpl(op *Op) string {
	name := tsName(op.Name)
	path := "`"
	for _, seg := range strings.Split(op.Path, "/") {
		if seg == "" {
			continue
		}
		if strings.HasPrefix(seg, ":") {
			path += "/${encodeURIComponent(" + tsName(seg[1:]) + ")}"
		} else {
			path += "/" + seg
		}
	}
	path += "`"
	if op.Socket {
		return name + ": () => base.replace(/^http/, \"ws\") + " + path
	}
	var query []string
	body := "undefined"
	for _, p := range op.Params {
		switch p.In {
		case "query":
			query = append(query, p.Name+": "+tsName(p.Name))
		case "body":
			body = tsName(p.Name)
		}
	}
	if len(query) > 0 {
		path += " + q({ " + strings.Join(query, ", ") + " })"
	}
	ps := a.tsParams(op)
	if el := op.Stream(); el != nil {
		ps = append(ps, "signal?: AbortSignal")
		return fmt.Sprintf("%s: (%s) => events<%s>(f, base, %q, %s, %s, signal)", name, strings.Join(ps, ", "), tsType(*el), op.Method, path, body)
	}
	ret := "void"
	if op.Returns != nil {
		ret = tsType(*op.Returns)
	}
	return fmt.Sprintf("%s: (%s) => call<%s>(f, base, %q, %s, %s)", name, strings.Join(ps, ", "), ret, op.Method, path, body)
}
